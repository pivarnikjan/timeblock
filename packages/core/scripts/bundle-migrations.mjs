// Bundles packages/core/drizzle/*.sql into src/db/migrations.ts, so both apps
// ship their migrations inside the code — the phone has no folder to read them from.
// Run after `drizzle-kit generate` (npm run db:generate does both).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, '..', 'drizzle');
const out = path.join(here, '..', 'src', 'db', 'migrations.ts');

export function readMigrations() {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.sql'))
    .sort()
    .map((name) => ({
      name,
      statements: readFileSync(path.join(dir, name), 'utf8')
        .replace(/\r\n/g, '\n')
        .split('--> statement-breakpoint')
        .map((s) => s.trim())
        .filter(Boolean),
    }));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const body = readMigrations()
    .map((m) => `  {\n    name: ${JSON.stringify(m.name)},\n    statements: [\n${m.statements.map((s) => `      ${JSON.stringify(s)},`).join('\n')}\n    ],\n  },`)
    .join('\n');
  writeFileSync(
    out,
    `// Generated by packages/core/scripts/bundle-migrations.mjs from packages/core/drizzle — do not edit.\n` +
      `// Regenerate with \`npm run db:generate\` (or \`node packages/core/scripts/bundle-migrations.mjs\`).\n\n` +
      `export interface Migration {\n  name: string;\n  statements: readonly string[];\n}\n\n` +
      `export const MIGRATIONS: readonly Migration[] = [\n${body}\n];\n`,
  );
  console.log(`bundled ${readMigrations().length} migrations into ${path.relative(process.cwd(), out)}`);
}
